(** The trapped completion (cont3's D′): the Cauchy filters carrying a
    bounded member, as a subcarrier 𝒯 X of 𝒞 X with the projected
    closeness equality, and the unit τ X : X ⇾ 𝒯 X factoring κ X.  The
    bornology is generated by the closures of unit images of bounded sets.
    𝒯 is a functor on UnifBorn with a dense unit, initial under a closed
    bornology; the reflection along dense reflecting maps, and with it the
    canonical completion, needs well containment, so the completion lives
    on 𝐖𝐂𝐔𝐧𝐢𝐟_gbl. *)


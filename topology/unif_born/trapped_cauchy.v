  Proof. apply (injective_compose_cancel (β X) _ _).
    change ((β X ∘ trapped_reflect) ∘ ι = β X ∘ τ X).
    rew trapped_reflect_factor, to_trapped_factor.
    exact (cauchy_reflect_spec ι).
  Qed.


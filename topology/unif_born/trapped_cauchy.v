    pose proof (wcunif_thicken Y (born_pt y)) as [U HU].
    rew (thicken_singleton U y) in HU.
    exists (born_preimage ι (@to_subset _ _ _ HU)).
    change (ι* (near U y) ∊ cauchy_reflect ι y).
